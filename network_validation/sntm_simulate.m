function out = sntm_simulate(cfg, sur, use_sur, p, seed, subset, init_rescale, sim_no)
% One network simulation with the fixed settings of sntm_config and the
% parameters in p (fields gamma1, lambda1, lambda2, delta, epsilon).
% use_sur = true runs the surrogate sur (make_surrogate) for flux, edge mass
% and W1; false runs the numeric model. Shared by run_sntm_cases.m and
% nelder_mead_network_recovery.m so both simulate the same way.

% flux_per_edge (SNTM_FLUX_PER_EDGE=1) is passed only when set, so runs with the
% original simulator code, which lacks the option, are unaffected
extra = {};
if cfg.flux_per_edge, extra = {'flux_per_edge', 1}; end
% SNTM_LAMBDA2_W1=lambda1: mass balance (W1) at lambda2 = lambda1, as in the
% surrogates' training data (flux keeps lambda2); needs the edited simulator
if cfg.lambda2_w1_is_lambda1, extra = [extra, {'lambda2_w1', p.lambda1}]; end

out = NetworkTransportModel(cfg.matdir, ...
    'beta', cfg.beta, 'gamma1', p.gamma1, 'gamma2', cfg.gamma2, 'frac', cfg.frac, ...
    'lambda1', p.lambda1, 'lambda2', p.lambda2, 'delta', p.delta, 'epsilon', p.epsilon, ...
    'L_int', cfg.L_int, 'L1', cfg.L1, 'L2', cfg.L2, 'L_ais', cfg.L_ais, 'L_syn', cfg.L_syn, ...
    'trange', cfg.trange, 'resmesh', cfg.resmesh, 'plotting', 0, ...
    'reltol', cfg.reltol, 'abstol', cfg.abstol, 'fsolvetol', cfg.fsolvetol, ...
    'init_rescale', init_rescale, 'init_path', {cfg.seeds(char(seed))}, ...
    'study', cfg.study, 'connectome_subset', char(subset), 'conn_thresh', cfg.conn_thresh, ...
    'sim_no', sim_no, ...
    'use_sr_flux', double(use_sur), 'sr_fun_flux', sur.flux_fun, 'sr_fun_em', sur.em_fun, ...
    'use_sr_w1', double(use_sur), 'sr_fun_w1', sur.w1_fun, extra{:});
end
